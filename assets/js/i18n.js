  let current = 'en';
  try { current = localStorage.getItem('sr_language') || 'en'; } catch (_) {}
  if (!STRINGS[current]) current = 'en';

  const interpolate = (value, vars = {}) => value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
  const t = (key, vars = {}) => interpolate(STRINGS[current]?.[key] || STRINGS.en[key] || key, vars);

  function apply(root = document) {
    document.documentElement.lang = current === 'fil' ? 'fil' : current;
    root.querySelectorAll('[data-i18n]').forEach(el => { const key = el.dataset.i18n; el.textContent = t(key); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)); });
    root.querySelectorAll('[data-i18n-content]').forEach(el => { el.setAttribute('content', t(el.dataset.i18nContent)); });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
    const titleKey = document.body?.dataset.titleKey;
    if (titleKey) document.title = t(titleKey);
    const switcher = document.getElementById('language-switcher');
    if (switcher) switcher.value = current;
    const toggle = document.getElementById('theme-toggle');
    if (toggle) updateThemeButton(toggle);
  }

  function updateThemeButton(button) {
    const dark = document.documentElement.dataset.theme === 'dark';
    button.setAttribute('aria-label', t(dark ? 'common.switchLight' : 'common.switchDark'));
    button.setAttribute('title', t(dark ? 'common.switchLight' : 'common.switchDark'));
    button.setAttribute('aria-pressed', String(dark));
    button.innerHTML = dark
      ? `<span aria-hidden="true">☀</span><span class="control-text">${t('common.lightMode')}</span>`
      : `<span aria-hidden="true">☾</span><span class="control-text">${t('common.darkMode')}</span>`;
  }

  function setLanguage(code) {
    if (!STRINGS[code]) return;
    current = code;
    try { localStorage.setItem('sr_language', code); } catch (_) {}
    apply(document);
    document.dispatchEvent(new CustomEvent('sr:languagechange', { detail: { language: current } }));
  }

  window.SR_TRANSLATIONS = STRINGS;
  window.SR_I18N = {
    languages: LANGUAGES,
    get language() { return current; },
    t,
    apply,
    setLanguage,
    updateThemeButton
  };
